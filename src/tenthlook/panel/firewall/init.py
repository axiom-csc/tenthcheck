"""`usepanel init -- <upstream cmd>`: ask an MCP server for tools/list, classify each tool by name/schema/annotations, and write a
STARTER policy for a human to review. It is a heuristic: it errs toward blocking (unclassified and destructive tools are
`allowed: false`; money-like tools get a cap of 0 until a human sets one; every write needs approval)."""
from __future__ import annotations

import asyncio
import json
import re
import sys
from pathlib import Path

from tenthlook.panel.firewall.types import FirewallError

READ = {"get", "list", "read", "search", "find", "describe", "show", "view", "fetch", "stat", "info", "head", "tree", "count",
        "lookup", "check", "status", "ls", "cat", "peek", "inspect"}
DESTRUCTIVE = {"delete", "remove", "drop", "truncate", "destroy", "purge", "wipe", "kill", "reset", "revoke", "terminate",
               "uninstall", "rm", "erase", "clear", "unlink", "rmdir"}
WRITE = {"write", "create", "update", "edit", "move", "rename", "set", "put", "post", "insert", "append", "upload", "add",
         "modify", "patch", "send", "execute", "run", "exec", "deploy", "commit", "push", "publish", "save", "mkdir", "copy",
         "install", "apply", "invoke", "call", "transfer", "submit", "approve"}
MONEY = {"refund", "pay", "charge", "transfer", "withdraw", "credit", "invoice", "buy", "purchase", "payout", "debit", "bill", "tip"}
AMOUNT_PARAMS = {"amount", "amount_usd", "total", "price", "cents", "value", "sum", "quantity", "qty"}
SQL_PARAMS = {"query", "sql", "statement"}
PATH_PARAMS = {"path", "paths", "file", "filepath", "source", "destination", "directory", "dir", "dest", "target", "filename"}


def tokens(name: str) -> list[str]:
    spaced = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", name)
    return [t for t in re.split(r"[^A-Za-z0-9]+", spaced.lower()) if t]


def classify(tool: dict) -> dict:
    name = tool["name"]
    toks, ann = set(tokens(name)), tool.get("annotations") or {}
    props = ((tool.get("inputSchema") or {}).get("properties") or {})
    pnames = {p.lower() for p in props}
    out: dict = {"name": name, "risk": "unknown", "why": ""}
    if toks & DESTRUCTIVE or ann.get("destructiveHint") is True:
        out.update(risk="destructive", why="name/annotation suggests it deletes or destroys")
    elif toks & MONEY:
        out.update(risk="write", why="moves money")
    elif toks & WRITE and not toks & READ:
        out.update(risk="write", why="name suggests it changes state")
    elif toks & READ or ann.get("readOnlyHint") is True:
        out.update(risk="read", why="name/annotation suggests read-only")
    if pnames & SQL_PARAMS and out["risk"] != "destructive":
        out["sql_arg"] = sorted(pnames & SQL_PARAMS)[0]
        if out["risk"] in ("read", "unknown"):
            out.update(risk="write" if out["risk"] == "unknown" else "read", why=out["why"] or "takes SQL: could modify data")
    if pnames & PATH_PARAMS:
        out["path_args"] = sorted(p for p in props if p.lower() in PATH_PARAMS)
    amt = sorted(p for p in props if p.lower() in AMOUNT_PARAMS)
    if amt and (toks & MONEY or "amount" in pnames or "amount_usd" in pnames):
        out["amount_field"] = amt[0]
    return out


def render(classified: list[dict], upstream_cmd: list[str]) -> str:
    L = ["# Panel starter policy: GENERATED BY A HEURISTIC. A human must review every line before relying on it.",
         "# Safe defaults: reads are allowed; every other tool needs human approval (mode: approval); destructive and",
         "# unclassified tools are blocked; money-like tools have a cap of 0 until you set a real one.",
         f"# Upstream: {' '.join(upstream_cmd)}", "version: \"0.1-draft\"", "reviewed: false   # set to true after you have reviewed this file",
         "mode: approval", "# database: ./app.db   # needed for row counts if a tool takes SQL", "actions:"]
    for c in classified:
        L.append(f"  {json.dumps(c['name'])}:")
        r = c["risk"]
        if r == "read":
            L.append("    risk: read")
        elif r == "destructive":
            L.append("    allowed: false   # REVIEW: looks destructive; delete this line only if you really want it callable")
            L.append("    risk: destructive")
        elif r == "write":
            L.append("    risk: write   # needs approval in `approval` mode")
        else:
            L.append("    allowed: false   # REVIEW: could not classify; decide what this tool does, then allow it")
        if c.get("amount_field"):
            L.append(f"    amount_field: {c['amount_field']}")
            L.append("    max_amount: 0   # REVIEW: set the largest amount this tool may ever move")
            L.append("    # consent_over_amount: 25")
        if c.get("sql_arg"):
            L.append(f"    sql_arg: {c['sql_arg']}   # SQL is parsed (sqlglot AST): DROP/ALTER/TRUNCATE, multi-statement, no-WHERE blocked")
            if r != "read":
                L.append("    max_rows: 10   # REVIEW: needs `database:` at the top so Panel can count rows first")
        if c.get("path_args"):
            L.append(f"    path_args: {json.dumps(c['path_args'])}")
            L.append("    allowed_roots: [\"/CHANGE/ME\"]   # REVIEW: the only folders this tool may touch (blocks everything until set)")
            L.append("    protected: {\"*\": [\"*/.env\", \"*/.ssh/*\", \"*/.git/*\"]}")
        if c["why"]:
            L.append(f"    note: {json.dumps('init: ' + c['why'])}")
    return "\n".join(L) + "\n"


async def _list_tools(cmd: list[str]) -> list[dict]:
    from tenthlook.panel.firewall.gateway import McpUpstream

    class Stub:
        async def on_upstream_message(self, up, msg): pass
        async def on_upstream_closed(self, up): pass
    up = McpUpstream("init", cmd, Stub())
    await up.start()
    try:
        r = await up.request("initialize", {"protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "panel-init", "version": "0.1"}}, 30)
        if "error" in r:
            raise FirewallError(f"upstream refused initialize: {r['error']}")
        await up.send({"jsonrpc": "2.0", "method": "notifications/initialized"})
        tools, cursor = [], None
        while True:
            r = await up.request("tools/list", {"cursor": cursor} if cursor else {}, 30)
            res = r.get("result") or {}
            tools += [t for t in res.get("tools", []) if isinstance(t, dict) and isinstance(t.get("name"), str)]
            cursor = res.get("nextCursor")
            if not cursor:
                return tools
    finally:
        await up.stop()


def run_init(a) -> int:
    cmd = list(a.upstream)
    if cmd and cmd[0] == "--":
        cmd = cmd[1:]
    if not cmd:
        raise FirewallError("usage: usepanel init [--out policy.yaml] -- <upstream command>")
    out = Path(a.out)
    if out.exists() and not a.force:
        raise FirewallError(f"{out} exists; use --force to overwrite")
    tools = asyncio.run(_list_tools(cmd))
    classified = [classify(t) for t in tools]
    out.write_text(render(classified, cmd))
    counts = {k: sum(1 for c in classified if c["risk"] == k) for k in ("read", "write", "destructive", "unknown")}
    print(f"wrote {out}: {len(tools)} tools ({counts['read']} read, {counts['write']} write, {counts['destructive']} destructive-blocked, "
          f"{counts['unknown']} unclassified-blocked).\nReview it, set reviewed: true, then: usepanel proxy --policy {out} -- {' '.join(cmd)}")
    return 0
